var (
	_ resource.Resource                = &webhookEndpointResource{}
	_ resource.ResourceWithImportState = &webhookEndpointResource{}
)

// NewWebhookEndpointResource returns harmoniq_webhook_endpoint.
func NewWebhookEndpointResource() resource.Resource { return &webhookEndpointResource{} }

type webhookEndpointResource struct{ client *client.Client }

type webhookEndpointModel struct {
	ID               types.String `tfsdk:"id"`
	Workspace        types.String `tfsdk:"workspace"`
	URL              types.String `tfsdk:"url"`
	Events           types.Set    `tfsdk:"events"`
	Active           types.Bool   `tfsdk:"active"`
	MaxRetries       types.Int64  `tfsdk:"max_retries"`
	BackoffCeilingMs types.Int64  `tfsdk:"backoff_ceiling_ms"`
	Secret           types.String `tfsdk:"secret"`
}

func (r *webhookEndpointResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_webhook_endpoint"
}

func (r *webhookEndpointResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		MarkdownDescription: "A webhook endpoint of a workspace. Deliveries are signed with `secret` " +
			"(HMAC-SHA256, `X-Harmoniq-Signature`), generated by the registry and known only at creation.",
		Attributes: map[string]schema.Attribute{
			"id": schema.StringAttribute{
				Computed:            true,
				MarkdownDescription: "Endpoint id.",
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
			"workspace": schema.StringAttribute{
				Required:            true,
				MarkdownDescription: "Workspace slug.",
				PlanModifiers:       []planmodifier.String{stringplanmodifier.RequiresReplace()},
			},
			"url": schema.StringAttribute{Required: true, MarkdownDescription: "HTTPS URL receiving the events."},
			"events": schema.SetAttribute{
				ElementType:         types.StringType,
				Required:            true,
				MarkdownDescription: "Events to send, e.g. `deploy.success`, `canary.auto_rolled_back`, or `*` for all.",
				Validators:          []validator.Set{setvalidator.SizeAtLeast(1)},
			},
			"active": schema.BoolAttribute{
				Optional:            true,
				Computed:            true,
				Default:             booldefault.StaticBool(true),
				MarkdownDescription: "Whether events are sent (default `true`).",
			},
			"max_retries": schema.Int64Attribute{
				Optional:            true,
				Computed:            true,
				Default:             int64default.StaticInt64(5),
				MarkdownDescription: "Retries before a delivery goes to the dead-letter queue (0–25, default 5).",
				Validators:          []validator.Int64{int64validator.Between(0, 25)},
			},
			"backoff_ceiling_ms": schema.Int64Attribute{
				Optional:            true,
				Computed:            true,
				Default:             int64default.StaticInt64(300000),
				MarkdownDescription: "Longest wait between retries in milliseconds (1000–3600000, default 300000).",
				Validators:          []validator.Int64{int64validator.Between(1000, 3600000)},
			},
			"secret": schema.StringAttribute{
				Computed:            true,
				Sensitive:           true,
				MarkdownDescription: "Signing secret, known only at creation (empty after an import).",
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
		},
	}
}

func (r *webhookEndpointResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	r.client = clientFrom(req.ProviderData, &resp.Diagnostics)
}

func (r *webhookEndpointResource) body(ctx context.Context, m webhookEndpointModel, diags *diag.Diagnostics) map[string]any {
	return map[string]any{
		"url":              m.URL.ValueString(),
		"events":           setStrings(ctx, m.Events, diags),
		"maxRetries":       m.MaxRetries.ValueInt64(),
		"backoffCeilingMs": m.BackoffCeilingMs.ValueInt64(),
	}
}

func (r *webhookEndpointResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan webhookEndpointModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	ws := plan.Workspace.ValueString()
	created, err := r.client.CreateWebhook(ctx, ws, r.body(ctx, plan, &resp.Diagnostics))
	if err != nil {
		resp.Diagnostics.AddError(apiErrorDetail("creating webhook endpoint", err))
		return
	}
	plan.ID = types.StringValue(created.ID)
	plan.Secret = types.StringValue(created.Secret)
	if !plan.Active.ValueBool() {
		if err := r.client.UpdateWebhook(ctx, ws, created.ID, map[string]any{"active": false}); err != nil {
			resp.Diagnostics.AddError(apiErrorDetail("deactivating webhook endpoint", err))
			return
		}
	}
	r.read(ctx, &plan, &resp.Diagnostics)
	resp.Diagnostics.Append(resp.State.Set(ctx, plan)...)
}

func (r *webhookEndpointResource) read(ctx context.Context, m *webhookEndpointModel, diags *diag.Diagnostics) bool {
	e, err := r.client.GetWebhook(ctx, m.Workspace.ValueString(), m.ID.ValueString())
	if client.IsNotFound(err) {
		return false
	}
	if err != nil {
		diags.AddError(apiErrorDetail("reading webhook endpoint", err))
		return true
	}
	m.URL = types.StringValue(e.URL)
	m.Events = stringSet(e.Events)
	m.Active = types.BoolValue(e.Active)
	m.MaxRetries = types.Int64Value(e.MaxRetries)
	m.BackoffCeilingMs = types.Int64Value(e.BackoffCeilingMs)
	if m.Secret.IsNull() || m.Secret.IsUnknown() {
		m.Secret = types.StringValue("")
	}
	return true
}

func (r *webhookEndpointResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state webhookEndpointModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if !r.read(ctx, &state, &resp.Diagnostics) {
		resp.State.RemoveResource(ctx)
		return
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, state)...)
}

func (r *webhookEndpointResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan webhookEndpointModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	body := r.body(ctx, plan, &resp.Diagnostics)
	body["active"] = plan.Active.ValueBool()
	if err := r.client.UpdateWebhook(ctx, plan.Workspace.ValueString(), plan.ID.ValueString(), body); err != nil {
		resp.Diagnostics.AddError(apiErrorDetail("updating webhook endpoint", err))
		return
	}
	r.read(ctx, &plan, &resp.Diagnostics)
	resp.Diagnostics.Append(resp.State.Set(ctx, plan)...)
}

func (r *webhookEndpointResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state webhookEndpointModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	err := r.client.DeleteWebhook(ctx, state.Workspace.ValueString(), state.ID.ValueString())
	if err != nil && !client.IsNotFound(err) {
		resp.Diagnostics.AddError(apiErrorDetail("deleting webhook endpoint", err))
	}
}

// ImportState takes "workspace/endpoint-id".
func (r *webhookEndpointResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	parts := splitID(req.ID, 2, "workspace/endpoint-id", &resp.Diagnostics)
	if parts == nil {
		return
	}
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("workspace"), parts[0])...)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), parts[1])...)
}
