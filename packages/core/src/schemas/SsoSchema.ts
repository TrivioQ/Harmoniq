import { z } from 'zod';

const role = z.enum(['viewer', 'developer', 'admin', 'owner']);
const domain = z
  .string()
  .trim()
  .toLowerCase()
  .regex(/^[a-z0-9-]+(\.[a-z0-9-]+)+$/, 'A domain like acme.com');

/** SSO-01..07, 22, 23, 26: a workspace's OIDC sign-in. */
export const OidcConfigSchema = z.object({
  issuer: z.string().url(),
  clientId: z.string().min(1).max(500),
  /** Write-only; omit on update to keep the stored secret. */
  clientSecret: z.string().min(1).max(2000).optional(),
  scopes: z.array(z.string().min(1)).default(['openid', 'email', 'profile']),
  /** Claim with the user's groups, e.g. `groups` (Okta, Keycloak) or `roles` (Entra). */
  groupsClaim: z.string().min(1).max(100).default('groups'),
  /** SSO-23: IdP group → role; the most permissive match wins. */
  roleMapping: z.record(z.string().min(1), role).default({}),
  /** SSO-22: users with these email domains join automatically. */
  trustedDomains: z.array(domain).max(50).default([]),
  defaultRole: role.exclude(['owner']).default('viewer'),
  /** SSO-26: members must sign in through this IdP (owners are exempt, as break-glass). */
  forceSso: z.boolean().default(false),
});

export type OidcConfig = z.infer<typeof OidcConfigSchema>;

/** SSO-15/16: a workspace's SAML 2.0 sign-in (the SP keypair is generated by the registry). */
export const SamlConfigSchema = z.object({
  idpEntityId: z.string().min(1).max(1000),
  idpSsoUrl: z.string().url(),
  idpSloUrl: z.string().url().optional(),
  /** IdP signing certificate, PEM or bare base64. */
  idpCert: z.string().min(100).max(20_000),
  nameIdFormat: z.string().default('urn:oasis:names:tc:SAML:1.1:nameid-format:emailAddress'),
  /** SSO-16: assertion attribute names; email falls back to an email-format NameID. */
  attributeMapping: z
    .object({
      email: z.string().min(1).optional(),
      name: z.string().min(1).optional(),
      groups: z.string().min(1).optional(),
    })
    .default({}),
  roleMapping: z.record(z.string().min(1), role).default({}),
  trustedDomains: z.array(domain).max(50).default([]),
  defaultRole: role.exclude(['owner']).default('viewer'),
  forceSso: z.boolean().default(false),
  /** SSO-09: accept IdP-initiated logins (no browser binding; off by default). */
  allowIdpInitiated: z.boolean().default(false),
});

export type SamlConfig = z.infer<typeof SamlConfigSchema>;

// ─── Organizations (ORG-05..07) ─────────────────────────────────────────────

/**
 * ORG-05: an organization's OIDC, inherited by its workspaces that have no SSO of their
 * own. Roles come from the organization's group rules, not a role mapping.
 */
export const OrgOidcConfigSchema = OidcConfigSchema.omit({ roleMapping: true, defaultRole: true });
export type OrgOidcConfig = z.infer<typeof OrgOidcConfigSchema>;

/** ORG-05/06: an organization's SAML 2.0. */
export const OrgSamlConfigSchema = SamlConfigSchema.omit({ roleMapping: true, defaultRole: true });
export type OrgSamlConfig = z.infer<typeof OrgSamlConfigSchema>;

const slug = z.string().regex(/^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/);
const group = z.string().trim().min(1).max(200);

/** ORG-07: members of an IdP group get a role in one of the organization's workspaces. */
export const OrgGroupRuleSchema = z.object({
  group,
  workspace: slug,
  role: role.exclude(['owner']),
});
export type OrgGroupRule = z.infer<typeof OrgGroupRuleSchema>;

/**
 * ORG-07: how IdP groups (from SCIM or the SSO assertion) become access. Members of
 * `adminGroups` become organization admins; rules grant workspace roles.
 */
export const OrgProvisioningSchema = z.object({
  rules: z.array(OrgGroupRuleSchema).max(200).default([]),
  adminGroups: z.array(group).max(50).default([]),
});
export type OrgProvisioning = z.infer<typeof OrgProvisioningSchema>;
