/**
 * OAS-03: generates the operations of the community Go and Python clients
 * (integrations/clients) from docs/openapi.json. Every REST operation under /api (except
 * browser sign-in) becomes one method named from its HTTP method and path:
 *
 *   POST /api/workspaces/{workspaceSlug}/modules/{moduleRef}/deploy
 *     Go:     c.PostWorkspacesModulesDeploy(ctx, workspaceSlug, moduleRef, body, query)
 *     Python: client.post_workspaces_modules_deploy(workspace_slug, module_ref, body=…, query=…)
 *
 * A path ending in a parameter adds `By<Param>`: GET …/modules/{moduleRef} is
 * GetWorkspacesModulesByModuleRef. Run `pnpm run clients:generate` after changing routes.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const spec = JSON.parse(readFileSync(join(root, 'docs/openapi.json'), 'utf8'));

const pascal = (s) =>
  s
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('');
const snake = (s) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^A-Za-z0-9]+/g, '_')
    .toLowerCase();
const camel = (s) => s[0].toLowerCase() + pascal(s).slice(1);

const operations = [];
for (const [path, methods] of Object.entries(spec.paths)) {
  if (!path.startsWith('/api/') || path.startsWith('/api/auth/')) continue;
  for (const [method, op] of Object.entries(methods)) {
    const segments = path.split('/').filter((s) => s && s !== 'api');
    const params = segments.filter((s) => s.startsWith('{')).map((s) => s.slice(1, -1));
    const statics = segments.filter((s) => !s.startsWith('{'));
    const trailing = [];
    for (let i = segments.length - 1; i >= 0 && segments[i].startsWith('{'); i--) {
      trailing.unshift(segments[i].slice(1, -1));
    }
    const name =
      pascal(method) +
      statics.map(pascal).join('') +
      (trailing.length ? 'By' + trailing.map(pascal).join('And') : '');
    operations.push({
      name,
      method: method.toUpperCase(),
      path,
      params,
      hasBody: !!op.requestBody,
      summary: `${method.toUpperCase()} ${path}`,
      tag: op.tags?.[0] ?? '',
    });
  }
}
operations.sort((a, b) => a.name.localeCompare(b.name));
const seen = new Set();
for (const op of operations) {
  if (seen.has(op.name)) throw new Error(`Two operations are named ${op.name}`);
  seen.add(op.name);
}

const header = (comment) =>
  `${comment} Copyright The Harmoniq Authors\n${comment} SPDX-License-Identifier: Apache-2.0\n\n` +
  `${comment} Code generated by scripts/generate-clients.mjs from docs/openapi.json. DO NOT EDIT.\n`;

// ─── Go ──────────────────────────────────────────────────────────────────────

const goPath = (op) => {
  const parts = op.path.split(/(\{[^}]+\})/).filter(Boolean);
  return parts
    .map((p) => (p.startsWith('{') ? `url.PathEscape(${camel(p.slice(1, -1))})` : JSON.stringify(p)))
    .join('+'); // gofmt style inside call arguments
};
const go = [
  header('//'),
  'package harmoniq\n',
  'import (\n\t"context"\n\t"net/url"\n)\n',
];
for (const op of operations) {
  const args = ['ctx context.Context', ...op.params.map((p) => `${camel(p)} string`)];
  if (op.hasBody) args.push('body any');
  args.push('query url.Values');
  go.push(
    `// ${op.name} calls ${op.summary}${op.tag ? ` (${op.tag})` : ''}.\n` +
      `func (c *Client) ${op.name}(${args.join(', ')}) (*Response, error) {\n` +
      `\treturn c.Do(ctx, ${JSON.stringify(op.method)}, ${goPath(op)}, ${op.hasBody ? 'body' : 'nil'}, query)\n` +
      `}\n`
  );
}
writeFileSync(join(root, 'integrations/clients/go/operations_gen.go'), go.join('\n'));

// ─── Python ──────────────────────────────────────────────────────────────────

const pyPath = (op) => {
  const parts = op.path.split(/(\{[^}]+\})/).filter(Boolean);
  return parts
    .map((p) => (p.startsWith('{') ? `_q(${snake(p.slice(1, -1))})` : JSON.stringify(p)))
    .join(' + ');
};
const py = [
  header('#'),
  'from typing import Any, Mapping, Optional\n',
  'from ._core import BaseClient, Response, quote_segment as _q\n\n',
  'class Client(BaseClient):',
  '    """Harmoniq registry client: one method per REST operation (see BaseClient)."""\n',
];
for (const op of operations) {
  const args = ['self', ...op.params.map(snake)];
  const kw = [...(op.hasBody ? ['body: Any = None'] : []), 'query: Optional[Mapping[str, Any]] = None'];
  py.push(
    `    def ${snake(op.name)}(${[...args, '*', ...kw].join(', ')}) -> Response:\n` +
      `        """${op.summary}${op.tag ? ` (${op.tag})` : ''}."""\n` +
      `        return self.request(${JSON.stringify(op.method)}, ${pyPath(op)}, ${op.hasBody ? 'body' : 'None'}, query)\n`
  );
}
writeFileSync(join(root, 'integrations/clients/python/harmoniq/_operations.py'), py.join('\n'));

console.log(`Generated ${operations.length} operations for the Go and Python clients.`);
